const originalValues = new Map();

function translatePage(language) {
  const lang = language === "en" ? "en" : "ru";
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n], [data-i18n-html], [data-i18n-attr]").forEach((element) => {
    if (!originalValues.has(element)) {
      const snapshot = { text: element.textContent, html: element.innerHTML, attrs: {} };
      const attrSpec = element.dataset.i18nAttr || "";
      attrSpec.split(";").filter(Boolean).forEach((part) => { const [name] = part.split(":"); snapshot.attrs[name] = element.getAttribute(name); });
      originalValues.set(element, snapshot);
    }
    const textKey = element.dataset.i18n;
    const htmlKey = element.dataset.i18nHtml;
    if (lang === "en") {
      if (textKey && translations.en[textKey] !== undefined) element.textContent = translations.en[textKey];
      if (htmlKey && translations.en[htmlKey] !== undefined) element.innerHTML = translations.en[htmlKey];
      (element.dataset.i18nAttr || "").split(";").filter(Boolean).forEach((part) => { const [name,key] = part.split(":"); if (translations.en[key] !== undefined) element.setAttribute(name, translations.en[key]); });
    } else {
      const original = originalValues.get(element);
      if (textKey) element.textContent = original.text;
      if (htmlKey) element.innerHTML = original.html;
      Object.entries(original.attrs).forEach(([name,value]) => element.setAttribute(name,value));
    }
  });
  document.querySelectorAll(".lang-button").forEach((button) => button.classList.toggle("active", button.dataset.language === lang));
  localStorage.setItem("vespa-language", lang);
  return lang;
}

